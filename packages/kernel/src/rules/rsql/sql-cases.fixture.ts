// The manual list of the `sql` front end (11-restricted-sql.md «怎么测», experiment 2): every
// refusal the spec names, with the outcome each must get. The fixed tests (./sql.test.ts) run each
// as written; the mutation tests (./sql.prop.test.ts) put each in other places and spellings and
// require the same outcome.
//
// `where` says how a case may be moved:
//   expr   an expression: `SELECT <sql> FROM runs`; may be put in a subquery, a CASE, a CTE
//   select a whole SELECT: may be put in a subquery or a CTE
//   stmt   a whole statement: spelling only (case, quoting, comments, line breaks)

export interface Case {
  readonly sql: string;
  /** `<code>/<reason>`, or `ok`. */
  readonly want: string;
  readonly where: "expr" | "select" | "stmt";
  readonly params?: readonly unknown[];
}

const SR = "sql_rejected";
const c = (where: Case["where"], want: string, sql: string, params?: readonly unknown[]): Case => ({
  sql,
  want,
  where,
  ...(params !== undefined ? { params } : {}),
});

