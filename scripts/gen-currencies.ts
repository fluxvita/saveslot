// Generates packages/kernel/src/schema/units-currency.ts from ISO 4217 "list one" (the current
// currency and funds codes), as published by the maintenance agency (SIX).
//
// docs/zh-CN/spec/03-data-model/10-types-and-units.md «精度与舍入»: the default scale of a currency
// is its ISO 4217 minor unit, generated from the table, never copied by hand.
//
//   node scripts/gen-currencies.ts [path/to/list-one.xml]
//
// Without a path the file is downloaded. Codes without a minor unit ("N.A.": precious metals, SDR,
// testing and "no currency" codes) are left out: a quantity in them has no default precision.

import { readFileSync, writeFileSync } from "node:fs";

const SOURCE =
  "https://www.six-group.com/dam/download/financial-information/data-center/iso-currrency/lists/list-one.xml";
const OUT = new URL("../packages/kernel/src/schema/units-currency.ts", import.meta.url);

/** The published date and the minor unit of every code that has one, from the XML text. */
export function parseListOne(xml: string): { published: string; minor: Map<string, number> } {
  const published = /<ISO_4217 Pblshd="(\d{4}-\d{2}-\d{2})">/.exec(xml)?.[1];
  if (published === undefined) throw new Error("no publication date");
  const minor = new Map<string, number>();
  for (const entry of xml.matchAll(/<CcyNtry>([\s\S]*?)<\/CcyNtry>/g)) {
    const body = entry[1] ?? "";
    const code = /<Ccy>([^<]*)<\/Ccy>/.exec(body)?.[1];
    // Entries without a code: territories with no universal currency.
    if (code === undefined) continue;
    if (!/^[A-Z]{3}$/.test(code)) throw new Error(`not a currency code: ${code}`);
    const units = /<CcyMnrUnts>([^<]*)<\/CcyMnrUnts>/.exec(body)?.[1];
    if (units === undefined) throw new Error(`no minor unit for ${code}`);
    if (units === "N.A.") continue;
    if (!/^[0-9]$/.test(units)) throw new Error(`minor unit of ${code}: ${units}`);
    const n = Number(units);
    // A code is listed once per country that uses it.
    if (minor.has(code) && minor.get(code) !== n) throw new Error(`${code}: two minor units`);
    minor.set(code, n);
  }
  if (minor.size === 0) throw new Error("no currencies");
  return { published, minor };
}

export function render(published: string, minor: ReadonlyMap<string, number>): string {
  const codes = [...minor.keys()].sort();
  const lines = [];
  let line = " ";
  for (const c of codes) {
    const item = ` ${c}: ${minor.get(c)},`;
    if (line.length + item.length > 100) {
      lines.push(line);
      line = " ";
    }
    line += item;
  }
  lines.push(line);
  return `// Generated by scripts/gen-currencies.ts from ISO 4217 list one. Do not edit by hand.
//
// Currency and funds codes with their minor unit (the default scale of a quantity in that
// currency; docs/zh-CN/spec/03-data-model/10-types-and-units.md «精度与舍入»). Codes without a
// minor unit are not listed.

/** Publication date of the list this file was generated from. */
export const ISO_4217_PUBLISHED = "${published}";

// biome-ignore format: generated table
export const CURRENCY_MINOR_UNITS: Readonly<Record<string, number>> = {
${lines.join("\n")}
};
`;
}

if (import.meta.main) {
  const path = process.argv[2];
  const xml = path !== undefined ? readFileSync(path, "utf8") : await (await fetch(SOURCE)).text();
  const { published, minor } = parseListOne(xml);
  writeFileSync(OUT, render(published, minor));
  console.log(`${minor.size} codes, published ${published}`);
}
